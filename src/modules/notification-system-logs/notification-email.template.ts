/**
 * Generic admin-initiated notification email template.
 *
 * Used by the Notification & System Logs module to deliver custom
 * messages from administrators to one or more named recipients.
 * The subject and body are operator-controlled; this template wraps
 * them in a consistent SecuraAI design shell.
 */
import {
  calloutBox,
  divider,
  para,
  renderBaseEmail,
  escapeHtml,
} from '../../common/email/email-base.template.js';

export type NotificationEmailInput = {
  appName: string;
  subject: string;
  /** Free-form message body. Newlines are converted to <br> automatically. */
  message: string;
  /** Optional — shown in the info callout to identify the sender */
  senderName?: string;
  inlineImages?: { name: string; cid: string }[];
};

function renderMessageBody(raw: string): string {
  return `<div style="color:#334263;font-size:15px;line-height:1.75;overflow-wrap:anywhere;">${escapeHtml(raw).replace(/\r\n|\r|\n/gu, '<br>')}</div>`;
}

export function renderNotificationEmail(input: NotificationEmailInput): string {
  const appName = escapeHtml(input.appName);
  const senderLine = input.senderName
    ? para(
        `This notification was sent to you by <strong>${escapeHtml(input.senderName)}</strong> via ${appName}.`,
      )
    : para(
        `This notification was sent to you by an authorized <strong>${appName}</strong> administrator.`,
      );

  const bodyHtml = [
    renderMessageBody(input.message),
    ...(input.inlineImages ?? []).map(
      (image) =>
        `<p><img src="cid:${escapeHtml(image.cid)}" alt="${escapeHtml(image.name)}" style="display:block;max-width:100%;height:auto;border:0;"></p>`,
    ),
    divider(),
    senderLine,
    calloutBox(
      'Do not reply to this email with passwords, access tokens, or other sensitive information. ' +
        'Legitimate administrators never request credentials by email.',
      'warning',
    ),
  ].join('');

  return renderBaseEmail({
    appName: input.appName,
    subject: input.subject,
    previewText: input.subject,
    badgeLabel: 'Security notification',
    badgeTone: 'brand',
    heading: input.subject,
    bodyHtml,
    footerNote:
      `This notification was generated by an authorized ${input.appName} administrator. ` +
      'Do not reply — your reply will not be delivered to the sender.',
    tagline: `Automated notification from ${input.appName}`,
  });
}
